#!/usr/bin/env python3
"""Create local hosting configuration, optionally start Docker Compose.

No external Python dependencies. Existing environment files are never replaced.
Run from any directory; all paths are relative to this repository.
"""

from __future__ import annotations

import argparse
import ipaddress
import os
from pathlib import Path
import re
import secrets
import shlex
import shutil
import subprocess


def public_domain(value: str) -> str:
    """Accept one DNS hostname, never a URL or Caddyfile fragment."""
    domain = value.lower()
    labels = domain.split(".")
    if len(domain) > 253 or len(labels) < 2 or any(
        not re.fullmatch(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?", label)
        for label in labels
    ):
        raise argparse.ArgumentTypeError("use a DNS name such as opt.example.com, without a scheme, path, or port")
    try:
        ipaddress.ip_address(domain)
    except ValueError:
        pass
    else:
        raise argparse.ArgumentTypeError("use a public DNS name, not an IP address")
    if domain.endswith((".localhost", ".local", ".internal", ".home.arpa")):
        raise argparse.ArgumentTypeError("use a public DNS name for automatic HTTPS")
    return domain


def create_env(path: Path, domain: str | None) -> bool:
    origin = f"https://{domain}" if domain else "http://localhost:8787"
    content = (
        "# Generated by deploy/bootstrap.py. Keep this file private.\n"
        f"APPLIED_OPT_TOKEN={secrets.token_urlsafe(32)}\n"
        f"APPLIED_OPT_PUBLIC_URL={origin}\n"
    )
    if domain:
        content += f"DOMAIN={domain}\n"
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        return False
    with os.fdopen(fd, "w", encoding="utf-8") as output:
        output.write(content)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--domain", type=public_domain, help="public DNS name for the Caddy HTTPS stack")
    parser.add_argument("--up", action="store_true", help="build and start the selected Docker Compose stack")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    env_name = ".env.production" if args.domain else ".env"
    compose_name = "compose.production.yaml" if args.domain else "compose.yaml"
    env_path = root / env_name
    if create_env(env_path, args.domain):
        print(f"Created {env_name}; the API token stays in that file.")
    else:
        print(f"Kept existing {env_name} unchanged; its current settings will be used.")
        if args.domain:
            # Do not silently deploy an existing file to a different domain.
            configured = None
            for line in env_path.read_text(encoding="utf-8").splitlines():
                if line.strip().startswith("DOMAIN="):
                    configured = line.strip().partition("=")[2].strip().strip("\"'")
            if configured != args.domain:
                parser.error(f"{env_name} has a different or missing DOMAIN; edit it explicitly or pass its existing domain")
    command = ["docker", "compose", "--env-file", env_name, "-f", compose_name, "up", "--build", "-d"]
    print(f"Run in {root}:\n  {shlex.join(command)}")
    print("Open the configured APPLIED_OPT_PUBLIC_URL and paste the file's APPLIED_OPT_TOKEN into the dashboard token field.")
    if not args.up:
        return 0
    if shutil.which("docker") is None:
        parser.error("Docker Compose is required for --up; configuration was saved. Install Docker and rerun the command above")
    return subprocess.run(command, cwd=root, check=False).returncode


if __name__ == "__main__":
    raise SystemExit(main())
